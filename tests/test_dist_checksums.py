"""Every published `.zip` in `dist/` has a checksum file, and it matches.

`SkyrimOutfit_LAS.zip.sha256` sat one build behind for two commits: the hashes
were regenerated by hand and the file kept describing an older zip, so anyone
who verified the download was told their copy was corrupt. The build now writes
its own checksum; this test keeps the rest honest and catches the same drift
anywhere in `dist/`.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
DIST = REPO / "dist"


def _checksum_files() -> list[Path]:
    return sorted(DIST.glob("*.zip.sha256"))


def test_dist_has_checksum_files():
    assert _checksum_files(), "no dist/*.zip.sha256 files found"


@pytest.mark.parametrize("sha_file", _checksum_files(),
                         ids=lambda p: p.name)
def test_published_zip_matches_its_checksum(sha_file: Path):
    fields = sha_file.read_text().split()
    assert len(fields) == 2, f"{sha_file.name}: want '<digest>  <path>'"
    digest, name = fields
    target = REPO / name
    if not target.exists():                       # bare-filename convention
        target = DIST / Path(name).name
    assert target.exists(), f"{sha_file.name} points at missing {name}"
    assert target.stat().st_size > 1024, f"{target.name} is not a real pack"
    assert hashlib.sha256(target.read_bytes()).hexdigest() == digest, (
        f"{sha_file.name} is stale — regenerate it from {target.name}")


def test_skyrim_outfit_checksum_is_written_by_the_build():
    """The build owns its checksum, so it cannot drift again."""
    src = (REPO / "tools" / "pd2-las" / "build_skyrim_outfit.py").read_text()
    assert "hashlib.sha256(" in src, "the build must hash the zip it just wrote"
    assert '{zipped.name}.sha256' in src, "the build must write dist/<zip>.sha256"
