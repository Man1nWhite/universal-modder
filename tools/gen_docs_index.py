#!/usr/bin/env python3
"""Generate `docs/README.md`: the index of every document under `docs/`.

    python tools/gen_docs_index.py            # rewrite docs/README.md
    python tools/gen_docs_index.py --check    # exit 1 if it is out of date (CI, `green`)

`knowledge/` has had a generated `INDEX.md` and a `--check` mode since it grew past fifty notes;
`docs/` did not, and by 2026-11 it held 200+ files across `audits/`, `pd2-las/` and `renders/`
with no entry point — an agent landing in the repository had to guess whether the install
contract was `docs/pd2-voice-mod-install.md` or `docs/pd2-las/HANDOFF.md`.

Every file is listed with its own first heading, so the index says what a document is for rather
than only what it is called. `docs/renders/` is listed as one entry: it is 130 capture folders
with its own curated README (`docs/renders/README.md`), and enumerating them here would bury the
guides. Renders are still counted, so a document that disappears from the index shows up as a
change in the count.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
INDEX = DOCS / "README.md"
SKIP_DIRS = {"renders"}
_HEADING = re.compile(r"^#\s+(.+)$", re.M)
_HEADER = """# Documentation index

_Generated by `python tools/gen_docs_index.py`; don't edit by hand. Regenerate after adding,
moving or renaming a document — `make -sC tools/pd2-las green` fails while this file is stale._

Start with [AGENTS.md](../AGENTS.md) if you are new here: it has one command per question.
The field notes (how a game was actually modded) live in [`knowledge/`](../knowledge/INDEX.md);
this directory holds the project's own guides, audits and evidence.

"""


def title_of(path: Path) -> str:
    """A document's first `#` heading, else its file name without the extension."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return path.stem.replace("-", " ")
    m = _HEADING.search(text)
    return m.group(1).strip() if m else path.stem.replace("-", " ")


def row(path: Path) -> str:
    rel = path.relative_to(DOCS).as_posix()
    return f"| [{title_of(path)}]({rel}) | `{rel}` |"


def documents() -> list[Path]:
    """Every Markdown file under docs/ except the index and the renders tree."""
    out = [p for p in sorted(DOCS.rglob("*.md"))
           if p.name != "README.md" or p.parent != DOCS]
    return [p for p in out if not (set(p.relative_to(DOCS).parts) & SKIP_DIRS)]


def render_folders() -> int:
    return sum(1 for p in (DOCS / "renders").rglob("README.md")) if (DOCS / "renders").is_dir() else 0


def build() -> str:
    docs = documents()
    top = [p for p in docs if p.parent == DOCS]
    sections: list[tuple[str, list[Path], str]] = [
        ("Guides", top, "The install contract, the voice-line tables and the format write-ups."),
        ("PAYDAY 2 work", sorted((DOCS / "pd2-las").rglob("*.md")),
         "Handoffs, decisions and format notes for the packs in `dist/`."),
        ("Audits", sorted((DOCS / "audits").rglob("*.md"), reverse=True),
         "Dated sweeps and second passes. Numbers in them are a snapshot of their day: take sizes, "
         "hashes and counts from `make -sC tools/pd2-las status`, never from a document."),
    ]
    lines = [_HEADER.rstrip(), ""]
    lines.append(f"{len(docs)} documents, plus the [render and capture index](renders/README.md) "
                 f"({render_folders()} archived sets).")
    for name, paths, blurb in sections:
        lines += ["", f"## {name}", "", blurb, "", "| Document | Path |", "|---|---|"]
        lines += [row(p) for p in paths]
    lines += ["", "## Renders and captures", "",
              "Screenshots and software renders, one folder per project / format / date: "
              "[`docs/renders/README.md`](renders/README.md) has the rules and the index.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when docs/README.md is out of date")
    args = ap.parse_args(argv)
    content = build()
    current = INDEX.read_text(encoding="utf-8") if INDEX.is_file() else ""
    if args.check:
        if current != content:
            print("FAIL: docs/README.md is out of date: run `python tools/gen_docs_index.py`", file=sys.stderr)
            return 1
        print(f"PASS: docs/README.md lists {len(documents())} documents")
        return 0
    INDEX.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {INDEX} ({len(documents())} documents)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
